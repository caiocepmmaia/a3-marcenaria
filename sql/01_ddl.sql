CREATE TABLE cliente (
                         cliente_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
                         nome       VARCHAR(120) NOT NULL,
                         cpf_cnpj   VARCHAR(18)  NOT NULL,
                         telefone   VARCHAR(20)  NOT NULL,
                         email      VARCHAR(120),
                         CONSTRAINT pk_cliente          PRIMARY KEY (cliente_id),
                         CONSTRAINT uk_cliente_cpf_cnpj UNIQUE (cpf_cnpj)
);

CREATE TABLE pedido (
                        pedido_id             INTEGER       GENERATED BY DEFAULT AS IDENTITY,
                        cliente_id            INTEGER       NOT NULL,
                        data_pedido           DATE          NOT NULL DEFAULT CURRENT_DATE,
                        data_entrega_prevista DATE          NOT NULL,
                        valor_total           NUMERIC(12,2) NOT NULL DEFAULT 0.00,
                        status                VARCHAR(20)   NOT NULL DEFAULT 'CADASTRADO',
                        CONSTRAINT pk_pedido          PRIMARY KEY (pedido_id),
                        CONSTRAINT fk_pedido_cliente  FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id) ON DELETE RESTRICT,
                        CONSTRAINT ck_pedido_datas    CHECK (data_entrega_prevista >= data_pedido),
                        CONSTRAINT ck_pedido_valor    CHECK (valor_total >= 0),
                        CONSTRAINT ck_pedido_status   CHECK (status IN ('CADASTRADO', 'EM_PRODUCAO', 'PRONTO', 'ENTREGUE', 'CANCELADO'))
);

CREATE TABLE item_pedido (
                             item_id         INTEGER       GENERATED BY DEFAULT AS IDENTITY,
                             pedido_id       INTEGER       NOT NULL,
                             descricao_movel VARCHAR(150)  NOT NULL,
                             ambiente        VARCHAR(60)   NOT NULL,
                             quantidade      INTEGER       NOT NULL,
                             valor_unitario  NUMERIC(12,2) NOT NULL,
                             CONSTRAINT pk_item_pedido        PRIMARY KEY (item_id),
                             CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (pedido_id) ON DELETE CASCADE,
                             CONSTRAINT ck_item_quantidade    CHECK (quantidade > 0),
                             CONSTRAINT ck_item_valor_unit    CHECK (valor_unitario > 0)
);

CREATE TABLE pagamento (
                           pagamento_id    INTEGER       GENERATED BY DEFAULT AS IDENTITY,
                           pedido_id       INTEGER       NOT NULL,
                           data_pagamento  DATE          NOT NULL DEFAULT CURRENT_DATE,
                           valor_pago      NUMERIC(12,2) NOT NULL,
                           forma_pagamento VARCHAR(20)   NOT NULL,
                           CONSTRAINT pk_pagamento        PRIMARY KEY (pagamento_id),
                           CONSTRAINT fk_pagamento_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (pedido_id) ON DELETE RESTRICT,
                           CONSTRAINT ck_pagamento_valor  CHECK (valor_pago > 0),
                           CONSTRAINT ck_pagamento_forma  CHECK (forma_pagamento IN ('PIX', 'TRANSFERENCIA', 'CARTAO', 'DINHEIRO'))
);

CREATE TABLE fornecedor (
                            fornecedor_id INTEGER      GENERATED BY DEFAULT AS IDENTITY,
                            razao_social  VARCHAR(150) NOT NULL,
                            cnpj          VARCHAR(18)  NOT NULL,
                            telefone      VARCHAR(20)  NOT NULL,
                            CONSTRAINT pk_fornecedor        PRIMARY KEY (fornecedor_id),
                            CONSTRAINT uk_fornecedor_razao  UNIQUE (razao_social),
                            CONSTRAINT uk_fornecedor_cnpj   UNIQUE (cnpj)
);

CREATE TABLE material (
                          material_id INTEGER      GENERATED BY DEFAULT AS IDENTITY,
                          nome        VARCHAR(120) NOT NULL,
                          unidade     VARCHAR(10)  NOT NULL,
                          CONSTRAINT pk_material         PRIMARY KEY (material_id),
                          CONSTRAINT uk_material_nome    UNIQUE (nome),
                          CONSTRAINT ck_material_unidade CHECK (unidade IN ('CHAPA', 'UN', 'M', 'L', 'KG'))
);

CREATE TABLE compra_material (
                                 compra_id      INTEGER       GENERATED BY DEFAULT AS IDENTITY,
                                 pedido_id      INTEGER       NOT NULL,
                                 material_id    INTEGER       NOT NULL,
                                 fornecedor_id  INTEGER       NOT NULL,
                                 data_compra    DATE          NOT NULL DEFAULT CURRENT_DATE,
                                 quantidade     NUMERIC(10,3) NOT NULL,
                                 custo_unitario NUMERIC(12,2) NOT NULL,
                                 CONSTRAINT pk_compra_material    PRIMARY KEY (compra_id),
                                 CONSTRAINT fk_compra_pedido      FOREIGN KEY (pedido_id)     REFERENCES pedido (pedido_id)         ON DELETE RESTRICT,
                                 CONSTRAINT fk_compra_material    FOREIGN KEY (material_id)   REFERENCES material (material_id)     ON DELETE RESTRICT,
                                 CONSTRAINT fk_compra_fornecedor  FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (fornecedor_id) ON DELETE RESTRICT,
                                 CONSTRAINT ck_compra_quantidade  CHECK (quantidade > 0),
                                 CONSTRAINT ck_compra_custo       CHECK (custo_unitario > 0)
);

CREATE TABLE auditoria_pedido (
                                  aud_id          INTEGER     GENERATED BY DEFAULT AS IDENTITY,
                                  pedido_id       INTEGER     NOT NULL,
                                  status_anterior VARCHAR(20),
                                  status_novo     VARCHAR(20) NOT NULL,
                                  usuario_banco   VARCHAR(60) NOT NULL DEFAULT CURRENT_USER,
                                  data_hora       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  CONSTRAINT pk_auditoria_pedido PRIMARY KEY (aud_id)
);